//! S3 cryptographic entropy startup and radio transition handling.

use core::cell::RefCell;
use embassy_sync::blocking_mutex::raw::CriticalSectionRawMutex;
use embassy_sync::blocking_mutex::Mutex;
use hmac::{Hmac, Mac};
use sha2::Sha256;

type HmacSha256 = Hmac<Sha256>;

static SHARED_PROVIDER: Mutex<CriticalSectionRawMutex, RefCell<Option<EntropyProvider>>> =
    Mutex::new(RefCell::new(None));
static RADIO_ENTROPY_FILL: Mutex<CriticalSectionRawMutex, RefCell<Option<fn(&mut [u8]) -> bool>>> =
    Mutex::new(RefCell::new(None));

/// Initialize the shared S3 provider with entropy sampled before radio startup.
pub fn initialize_global(seed: [u8; 32]) {
    SHARED_PROVIDER.lock(|provider| {
        let mut provider = provider.borrow_mut();
        let mut initialized = EntropyProvider::new();
        initialized.seed_from_adc(seed);
        *provider = Some(initialized);
    });
}

/// Install a chip-specific RF entropy reader used after the radio starts.
pub fn set_radio_entropy_source(source: fn(&mut [u8]) -> bool) {
    RADIO_ENTROPY_FILL.lock(|reader| *reader.borrow_mut() = Some(source));
}

/// Mark the point where the Matter wireless stack is about to start Wi-Fi/BLE.
pub fn mark_radio_starting() -> Result<(), EntropyError> {
    SHARED_PROVIDER.lock(|provider| {
        provider
            .borrow_mut()
            .as_mut()
            .ok_or(EntropyError::Unseeded)?
            .start_radio()
    })
}

/// Fill bytes from the shared provider and mix hardware RNG output after radio startup.
pub fn fill_global(output: &mut [u8]) -> Result<(), EntropyError> {
    let radio_started = SHARED_PROVIDER.lock(|provider| {
        provider
            .borrow()
            .as_ref()
            .is_some_and(|provider| provider.radio_started)
    });
    if radio_started {
        let reader = RADIO_ENTROPY_FILL.lock(|reader| *reader.borrow());
        if let Some(reader) = reader {
            let mut radio_entropy = [0; 32];
            if reader(&mut radio_entropy) {
                SHARED_PROVIDER.lock(|provider| {
                    if let Some(provider) = provider.borrow_mut().as_mut() {
                        provider.set_rf_source_available(true);
                        let _ = provider.reseed_from_rf(radio_entropy);
                    }
                });
            }
        }
    }
    SHARED_PROVIDER.lock(|provider| {
        let mut provider = provider.borrow_mut();
        let provider = provider.as_mut().ok_or(EntropyError::Unseeded)?;
        provider.fill_secure(output)
    })
}

/// Secure random output cannot be provided until entropy is seeded and released.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum EntropyError {
    Unseeded,
    SeedSourceNotReleased,
    RadioEntropyUnavailable,
}

/// HMAC-DRBG seeded from the startup ADC and optionally reseeded from RF entropy.
pub struct EntropyProvider {
    key: [u8; 32],
    value: [u8; 32],
    seeded: bool,
    seed_source_released: bool,
    radio_started: bool,
    rf_source_available: bool,
}

impl EntropyProvider {
    /// Create a provider that cannot produce bytes until an ADC seed is supplied.
    pub const fn new() -> Self {
        Self {
            key: [0; 32],
            value: [1; 32],
            seeded: false,
            seed_source_released: false,
            radio_started: false,
            rf_source_available: false,
        }
    }

    /// Seed the DRBG from sampled ADC entropy, then release the ADC resource.
    pub fn seed_from_adc(&mut self, entropy: [u8; 32]) {
        self.update(Some(&entropy));
        self.seeded = true;
        self.seed_source_released = true;
    }

    /// Start radio use only after releasing the ADC entropy source.
    pub fn start_radio(&mut self) -> Result<(), EntropyError> {
        if !self.seed_source_released {
            return Err(EntropyError::SeedSourceNotReleased);
        }
        self.radio_started = true;
        Ok(())
    }

    /// Record whether RF-backed entropy is currently available.
    pub fn set_rf_source_available(&mut self, available: bool) {
        self.rf_source_available = available && self.radio_started;
    }

    /// Reseed the DRBG with RF entropy when the radio source is available.
    pub fn reseed_from_rf(&mut self, entropy: [u8; 32]) -> Result<(), EntropyError> {
        if !self.rf_source_available {
            return Err(EntropyError::RadioEntropyUnavailable);
        }
        self.update(Some(&entropy));
        Ok(())
    }

    /// Fill a caller's buffer with cryptographically generated bytes.
    pub fn fill_secure(&mut self, output: &mut [u8]) -> Result<(), EntropyError> {
        if !self.seeded {
            return Err(EntropyError::Unseeded);
        }
        if !self.seed_source_released {
            return Err(EntropyError::SeedSourceNotReleased);
        }

        for chunk in output.chunks_mut(32) {
            self.value = hmac_sha256(&self.key, &[&self.value]);
            chunk.copy_from_slice(&self.value[..chunk.len()]);
        }
        self.update(None);
        Ok(())
    }

    /// Whether the ADC peripheral has been released for radio startup.
    pub const fn seed_source_released(&self) -> bool {
        self.seed_source_released
    }

    fn update(&mut self, provided_data: Option<&[u8]>) {
        let separator = [0u8];
        self.key = hmac_sha256(
            &self.key,
            &[&self.value, &separator, provided_data.unwrap_or(&[])],
        );
        self.value = hmac_sha256(&self.key, &[&self.value]);
        if let Some(provided_data) = provided_data {
            let separator = [1u8];
            self.key = hmac_sha256(&self.key, &[&self.value, &separator, provided_data]);
            self.value = hmac_sha256(&self.key, &[&self.value]);
        }
    }
}

fn hmac_sha256(key: &[u8], parts: &[&[u8]]) -> [u8; 32] {
    let mut mac = HmacSha256::new_from_slice(key).expect("HMAC accepts keys of any size");
    for part in parts {
        mac.update(part);
    }
    mac.finalize().into_bytes().into()
}

#[cfg(test)]
mod tests {
    use super::{fill_global, initialize_global, EntropyError, EntropyProvider};

    #[test]
    fn handles_secure_startup_and_radio_transition() {
        // Arrange
        let mut provider = EntropyProvider::new();
        let mut output = [0u8; 32];

        // Act
        let before_seed = provider.fill_secure(&mut output);

        // Assert
        assert_eq!(before_seed, Err(EntropyError::Unseeded));

        // Act
        provider.seed_from_adc([0x5a; 32]);
        let radio_start = provider.start_radio();
        provider.set_rf_source_available(false);
        let after_seed_without_radio_entropy = provider.fill_secure(&mut output);

        // Assert
        assert!(provider.seed_source_released());
        assert!(radio_start.is_ok());
        assert!(after_seed_without_radio_entropy.is_ok());
        assert_ne!(output, [0; 32]);
    }

    #[test]
    fn shares_seeded_entropy_with_secure_consumers() {
        // Arrange
        initialize_global([0x31; 32]);
        let mut matter_output = [0; 32];
        let mut webrtc_output = [0; 32];

        // Act
        let matter_result = fill_global(&mut matter_output);
        let webrtc_result = fill_global(&mut webrtc_output);

        // Assert
        assert!(matter_result.is_ok());
        assert!(webrtc_result.is_ok());
        assert_ne!(matter_output, [0; 32]);
        assert_ne!(webrtc_output, [0; 32]);
        assert_ne!(matter_output, webrtc_output);
    }
}
